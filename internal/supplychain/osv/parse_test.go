func TestLongLineFailsRatherThanTruncating(t *testing.T) {
	long := "# " + strings.Repeat("a", maxLockfileLineBytes+1)
	data := []byte(long + "\nrequests==2.19.0\n")

	if coords, unpinned, _, err := ParseRequirementsTxt(data); err == nil {
		t.Fatalf("requirements.txt: got %v (unpinned %d) and no error, want a failure", coords, unpinned)
	} else if !errors.Is(err, bufio.ErrTooLong) {
		t.Fatalf("requirements.txt: got %v, want bufio.ErrTooLong", err)
	}
	if _, err := ParseGoSum(data); !errors.Is(err, bufio.ErrTooLong) {
		t.Fatalf("go.sum: got %v, want bufio.ErrTooLong", err)
	}
	if _, _, err := ParseGoMod(data); !errors.Is(err, bufio.ErrTooLong) {
		t.Fatalf("go.mod: got %v, want bufio.ErrTooLong", err)
	}
	if _, err := ParseCargoLock(data); !errors.Is(err, bufio.ErrTooLong) {
		t.Fatalf("Cargo.lock: got %v, want bufio.ErrTooLong", err)
	}
	if _, _, err := ParsePoetryLock(data); !errors.Is(err, bufio.ErrTooLong) {
		t.Fatalf("poetry.lock: got %v, want bufio.ErrTooLong", err)
	}
}

func TestLongButReadableLineParses(t *testing.T) {
	data := []byte("# " + strings.Repeat("a", 200<<10) + "\nrequests==2.19.0\n")
	got, _, _, err := ParseRequirementsTxt(data)
	if err != nil {
		t.Fatal(err)
	}
	if !hasCoord(got, "PyPI", "requests", "2.19.0") {
		t.Fatalf("missing requests after a 200 KiB comment line: %v", got)
	}
}

// Look up the module selected by replace and report local replacements as unresolved
func TestParseGoModReplace(t *testing.T) {
	data := []byte(`module example.com/app

require (
	example.com/a v1.0.0
	example.com/b v1.0.0
)

replace example.com/a => example.com/fork v1.2.3
replace example.com/b => ../b
`)
	got, notes, err := ParseGoMod(data)
	if err != nil {
		t.Fatal(err)
	}
	if !hasCoord(got, "Go", "example.com/fork", "v1.2.3") || hasCoord(got, "Go", "example.com/a", "v1.0.0") {
		t.Fatalf("want the replacement looked up instead of the required module: %v", got)
	}
	if len(notes) != 1 || !strings.Contains(notes[0], "example.com/b") {
		t.Fatalf("want one note for the local-path replacement, got %v", notes)
	}
}

// Exclude git and local dependencies because registry metadata does not describe their bytes
func TestParsePackageLockNonRegistrySources(t *testing.T) {
	data := []byte(`{"packages": {
  "": {"name": "app"},
  "node_modules/from-git": {"version": "1.0.0", "resolved": "git+https://github.com/x/from-git.git#abc123"},
  "node_modules/from-disk": {"version": "1.0.0", "resolved": "file:../from-disk"},
  "node_modules/from-registry": {"version": "1.0.0", "resolved": "https://registry.npmjs.org/from-registry/-/from-registry-1.0.0.tgz"}
}}`)
	got, notes, err := ParsePackageLock(data)
	if err != nil {
		t.Fatal(err)
	}
	if len(got) != 1 || !hasCoord(got, "npm", "from-registry", "1.0.0") {
		t.Fatalf("want only the registry package looked up, got %v", got)
	}
	if len(notes) != 2 {
		t.Fatalf("want a note for each non-registry source, got %v", notes)
	}
}

// Poetry git, URL, file, and directory sources are also outside registry metadata
